/** Flatten a section tree into a flat list */
function flattenSections(section: INDSection): INDSection[] {
  const result: INDSection[] = [section];
  if (section.children) {
    for (const child of section.children) {
      result.push(...flattenSections(child));
    }
  }
  return result;
}

/** Count total and required sections */
function countSections(modules: INDSection[]): { total: number; required: number } {
  let total = 0;
  let required = 0;
  for (const mod of modules) {
    const flat = flattenSections(mod);
    for (const s of flat) {
      // Only count leaf or meaningful non-container sections
      if (s.estimatedHours > 0 || !s.children || s.children.length === 0) {
        total++;
        if (s.required) required++;
      }
    }
  }
  return { total, required };
}

/** Sum estimated hours across all sections */
function totalHours(modules: INDSection[]): number {
  let hours = 0;
  for (const mod of modules) {
    for (const s of flattenSections(mod)) {
      hours += s.estimatedHours;
    }
  }
  return hours;
}

/**
 * Build the complete IND eCTD Package Definition.
 * This is the single source of truth for every section in an IND filing.
 */
export function buildINDPackageDefinition(): INDPackageDefinition {
  const modules = [MODULE_1, MODULE_2, MODULE_3, MODULE_4, MODULE_5];
  const counts = countSections(modules);
  return {
    submissionType: 'IND',
    ectdVersion: '4.0',
    agency: 'FDA',
    totalSections: counts.total,
    requiredSections: counts.required,
    estimatedTotalHours: totalHours(modules),
    modules,
  };
}

/**
 * Get a flat list of all IND sections (for search, filtering, status tracking).
 */
export function getAllINDSections(): INDSection[] {
  const pkg = buildINDPackageDefinition();
  return pkg.modules.flatMap(flattenSections);
}

/**
 * Get all sections that Lumen Cortex can AI-draft.
 */
export function getAIDraftableSections(): INDSection[] {
  return getAllINDSections().filter(s => s.aiDraftable);
}

/**
 * Get sections required for initial IND filing.
 */
export function getRequiredSections(): INDSection[] {
  return getAllINDSections().filter(s => s.required);
}

/**
 * Lookup a section by its eCTD code.
 */
export function getSectionByCode(code: string): INDSection | undefined {
  return getAllINDSections().find(s => s.code === code);
}

/**
 * Get sections mapped to a specific pyramid task.
 */
export function getSectionsForPyramidTask(taskId: string): INDSection[] {
  return getAllINDSections().filter(s => s.pyramidTaskId === taskId);
}

/**
 * Bridge: Given an IND pyramid task, return the eCTD sections it produces.
 * This is the key connector between the workflow engine and the eCTD structure.
 */
export function pyramidToECTDMap(): Map<string, INDSection[]> {
  const map = new Map<string, INDSection[]>();
  for (const section of getAllINDSections()) {
    if (section.pyramidTaskId) {
      const existing = map.get(section.pyramidTaskId) || [];
      existing.push(section);
      map.set(section.pyramidTaskId, existing);
    }
  }
  return map;
}

/**
 * Get the module-level progress summary for an IND submission.
 * Takes a map of section code → status and returns per-module stats.
 */
export function getModuleProgress(statusMap: Map<string, SectionStatus>): Array<{
  module: CTDModule;
  title: string;
  total: number;
  completed: number;
  inProgress: number;
  percentage: number;
}> {
  const pkg = buildINDPackageDefinition();
  return pkg.modules.map(mod => {
    const sections = flattenSections(mod).filter(
      s => s.estimatedHours > 0 || !s.children || s.children.length === 0
    );
    let completed = 0;
    let inProgress = 0;
    for (const s of sections) {
      const status = statusMap.get(s.code);
      if (status === 'approved' || status === 'signed' || status === 'locked') completed++;
      else if (status && status !== 'not_started') inProgress++;
    }
    return {
      module: mod.module,
      title: mod.title,
      total: sections.length,
      completed,
      inProgress,
      percentage: sections.length > 0 ? Math.round((completed / sections.length) * 100) : 0,
    };
  });
}
