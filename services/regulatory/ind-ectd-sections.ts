/** eCTD top-level module identifier */
export type CTDModule = 'M1' | 'M2' | 'M3' | 'M4' | 'M5';

/** Section lifecycle for authoring workflow */
export type SectionStatus =
  | 'not_started'
  | 'data_gathering'
  | 'drafting'
  | 'internal_review'
  | 'revision'
  | 'qa_review'
  | 'approved'
  | 'signed'
  | 'locked';

/** Document format for the section */
export type DocumentFormat = 'pdf' | 'xml' | 'docx' | 'json' | 'xpt';

/** Authoring mode */
export type AuthoringMode = 'ai_draft' | 'manual' | 'template_fill' | 'data_import' | 'form';

/** A single eCTD section definition */
export interface INDSection {
  /** eCTD module code (e.g., "m1.2", "m2.3.S.1") */
  code: string;
  /** Human-readable section title */
  title: string;
  /** Parent eCTD code (null for top-level modules) */
  parentCode: string | null;
  /** CTD Module (M1-M5) */
  module: CTDModule;
  /** Depth in hierarchy (0=module, 1=section, 2=subsection, 3=leaf) */
  depth: number;
  /** Linked IND Pyramid task ID (for workflow engine bridge) */
  pyramidTaskId: string | null;
  /** Required for initial IND filing */
  required: boolean;
  /** Required for IND amendments */
  requiredForAmendment: boolean;
  /** Document format */
  format: DocumentFormat;
  /** How this section is authored */
  authoringMode: AuthoringMode;
  /** Whether Lumen Cortex can AI-draft this section */
  aiDraftable: boolean;
  /** Responsible role */
  role: string;
  /** Regulatory reference (CFR citation) */
  regulatoryRef: string;
  /** Brief description of content requirements */
  description: string;
  /** Child sections (recursive tree) */
  children?: INDSection[];
  /** eCTD 4.0 Context of Use code (ICH M8) */
  contextOfUse?: string;
  /** Estimated authoring hours */
  estimatedHours: number;
}

/** Complete IND eCTD package definition */
export interface INDPackageDefinition {
  submissionType: 'IND';
  ectdVersion: '4.0';
  agency: 'FDA';
  totalSections: number;
  requiredSections: number;
  estimatedTotalHours: number;
  modules: INDSection[];
}

