-- 0) Schema
CREATE SCHEMA IF NOT EXISTS evidence;

-- ============================================================================
-- 1) evidence.claims — atomic, typed, versioned claim records
-- ============================================================================

CREATE TABLE IF NOT EXISTS evidence.claims (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    program_id      UUID NOT NULL,          -- FK to core.programs(id)
    claim_type      TEXT NOT NULL,           -- 'efficacy', 'safety', 'endpoint', 'regulatory', 'procedural'
    claim_text      TEXT NOT NULL,           -- the natural-language assertion
    structured      JSONB NOT NULL DEFAULT '{}',
        -- typed fields: { entity, field, value, unit, comparator, timeframe }
    section_ref     TEXT,                    -- e.g. 'Module 2.7.3', 'CSR §12.4'
    version         INT NOT NULL DEFAULT 1, -- bump on correction
    supersedes_id   UUID REFERENCES evidence.claims(id),
    status          TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'superseded', 'retracted', 'draft')),
    confidence      NUMERIC(5,4),           -- 0.0000–1.0000, computed by scoring
    created_by      TEXT NOT NULL DEFAULT 'system',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE evidence.claims IS
    'Atomic typed claims extracted or generated by the platform. Every output assertion.';

-- ============================================================================
-- 2) evidence.sources — where evidence originates
-- ============================================================================

CREATE TABLE IF NOT EXISTS evidence.sources (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    program_id      UUID NOT NULL,
    source_type     TEXT NOT NULL,           -- 'csr_section', 'guideline', 'dataset_row', 'model_output', 'literature', 'sap'
    source_ref      TEXT NOT NULL,           -- human-readable ref: 'CSR §12.4', 'ICH E6(R2) §5.18', 'ADSL row 42'
    source_uri      TEXT,                    -- machine-resolvable: blob path, DB row pointer, URL
    content_hash    TEXT,                    -- sha256 of source content at time of capture
    metadata        JSONB NOT NULL DEFAULT '{}',
        -- { document_id, page, paragraph, table_id, nct_id, version }
    captured_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE evidence.sources IS
    'Evidence sources: CSR sections, guidelines, datasets, model outputs. Immutable captures.';

-- ============================================================================
-- 3) evidence.support — many-to-many claim ↔ source with strength
-- ============================================================================

CREATE TABLE IF NOT EXISTS evidence.support (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    claim_id        UUID NOT NULL REFERENCES evidence.claims(id),
    source_id       UUID NOT NULL REFERENCES evidence.sources(id),
    program_id      UUID NOT NULL,
    support_type    TEXT NOT NULL DEFAULT 'supports'
        CHECK (support_type IN ('supports', 'contradicts', 'qualifies', 'neutral')),
    strength        NUMERIC(5,4) NOT NULL DEFAULT 0.5000,
        -- 0 = no support, 1 = definitive
    span_start      INT,                    -- character offset in source content
    span_end        INT,
    annotation      TEXT,                   -- human/model explanation of the link
    created_by      TEXT NOT NULL DEFAULT 'system',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (claim_id, source_id, support_type)
);

COMMENT ON TABLE evidence.support IS
    'Many-to-many links between claims and sources. Includes strength score + span pointers.';

-- ============================================================================
-- 4) evidence.derivations — claim A derived from claim B (reasoning chains)
-- ============================================================================

CREATE TABLE IF NOT EXISTS evidence.derivations (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    program_id      UUID NOT NULL,
    derived_claim_id    UUID NOT NULL REFERENCES evidence.claims(id),
    source_claim_id     UUID NOT NULL REFERENCES evidence.claims(id),
    derivation_type     TEXT NOT NULL DEFAULT 'inference'
        CHECK (derivation_type IN ('inference', 'aggregation', 'correction', 'contradiction', 'synthesis')),
    reasoning       TEXT,                   -- explanation of the derivation step
    model_id        TEXT,                   -- which model/agent produced this
    created_by      TEXT NOT NULL DEFAULT 'system',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (derived_claim_id, source_claim_id, derivation_type),
    CHECK (derived_claim_id != source_claim_id)
);

COMMENT ON TABLE evidence.derivations IS
    'Reasoning lineage: how claim A was derived from claim B. Enables chain-of-thought replay.';

-- ============================================================================
-- 5) evidence.provenance — execution → claim traceability
-- ============================================================================

CREATE TABLE IF NOT EXISTS evidence.provenance (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    program_id          UUID NOT NULL,
    claim_id            UUID REFERENCES evidence.claims(id),
    source_id           UUID REFERENCES evidence.sources(id),
    -- Execution context (nullable — at least one must be set)
    workflow_run_id     UUID,               -- FK to orchestration.workflow_runs(id)
    step_run_id         UUID,               -- FK to orchestration.step_runs(id)
    batch_id            UUID,               -- FK to vault.review_batches(batch_id)
    event_type          TEXT NOT NULL,       -- 'claim_extracted', 'source_captured', 'claim_generated', 'claim_scored'
    actor               TEXT NOT NULL DEFAULT 'system',
    request_id          TEXT,               -- correlates to X-Request-Id header
    metadata            JSONB NOT NULL DEFAULT '{}',
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (claim_id IS NOT NULL OR source_id IS NOT NULL)
);

COMMENT ON TABLE evidence.provenance IS
    'Execution provenance: which workflow/step/batch created which claim or source. Forensic bridge.';

-- ============================================================================
-- 6) evidence.hash_ledger — tamper-evident content fingerprints
-- ============================================================================

CREATE TABLE IF NOT EXISTS evidence.hash_ledger (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    program_id      UUID NOT NULL,
    entity_type     TEXT NOT NULL,           -- 'claim', 'source', 'support', 'derivation', 'document'
    entity_id       UUID NOT NULL,
    content_hash    TEXT NOT NULL,           -- sha256 of canonical content
    prev_hash       TEXT,                    -- hash of previous version (chain)
    algorithm       TEXT NOT NULL DEFAULT 'sha256',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE evidence.hash_ledger IS
    'Append-only tamper-evidence ledger. Content hashes for claims, sources, and artifacts.';

