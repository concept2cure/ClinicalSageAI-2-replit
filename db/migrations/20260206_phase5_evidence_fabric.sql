-- Claim with all supporting sources (denormalized for read)
CREATE OR REPLACE VIEW evidence.v_claim_support AS
SELECT
    c.id AS claim_id,
    c.program_id,
    c.claim_type,
    c.claim_text,
    c.confidence,
    c.status AS claim_status,
    c.section_ref,
    s.id AS support_id,
    s.support_type,
    s.strength,
    src.id AS source_id,
    src.source_type,
    src.source_ref,
    src.content_hash AS source_hash
FROM evidence.claims c
JOIN evidence.support s ON s.claim_id = c.id
JOIN evidence.sources src ON src.id = s.source_id
WHERE c.status = 'active';

COMMENT ON VIEW evidence.v_claim_support IS
    'Denormalized view: active claims with all supporting/contradicting sources.';

-- Derivation chain (one level deep — use recursive CTE in app layer for full chain)
CREATE OR REPLACE VIEW evidence.v_derivation_chain AS
SELECT
    d.id AS derivation_id,
    d.program_id,
    d.derivation_type,
    d.reasoning,
    dc.id AS derived_claim_id,
    dc.claim_text AS derived_text,
    dc.claim_type AS derived_type,
    sc.id AS source_claim_id,
    sc.claim_text AS source_text,
    sc.claim_type AS source_type
FROM evidence.derivations d
JOIN evidence.claims dc ON dc.id = d.derived_claim_id
JOIN evidence.claims sc ON sc.id = d.source_claim_id;

COMMENT ON VIEW evidence.v_derivation_chain IS
    'One-level derivation chain: derived claim ← source claim with reasoning.';

-- Execution provenance (full trace: who/what/when → which evidence)
CREATE OR REPLACE VIEW evidence.v_execution_provenance AS
SELECT
    p.id AS provenance_id,
    p.program_id,
    p.event_type,
    p.actor,
    p.request_id,
    p.created_at,
    p.workflow_run_id,
    p.step_run_id,
    p.batch_id,
    c.id AS claim_id,
    c.claim_text,
    c.claim_type,
    src.id AS source_id,
    src.source_ref,
    src.source_type
FROM evidence.provenance p
LEFT JOIN evidence.claims c ON c.id = p.claim_id
LEFT JOIN evidence.sources src ON src.id = p.source_id;

COMMENT ON VIEW evidence.v_execution_provenance IS
    'Full execution provenance: workflow/step/batch → claim/source with actor + request_id.';

