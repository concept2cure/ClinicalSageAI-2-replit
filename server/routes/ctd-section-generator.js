// Generate CTD section content using OpenAI
async function generateCtdSectionContent(sectionCode, sectionTitle, description, region = 'US') {
  try {
    // Check if OpenAI API key is available
    if (!process.env.OPENAI_API_KEY) {
      throw new Error('OpenAI API key not configured. Please provide your OpenAI API key.');
    }

    const { OpenAI } = require('openai');
    const openai = new OpenAI({ apiKey: process.env.OPENAI_API_KEY });

    const template = CTD_SECTION_TEMPLATES[sectionCode];
    if (!template) {
      throw new Error(`No template found for CTD section ${sectionCode}`);
    }

    // Create comprehensive prompt based on the field manual
    const prompt = `You are an expert regulatory medical writer creating content for a Common Technical Document (CTD) submission. 

Generate authentic, regulatory-compliant content for:
Section: ${sectionCode} - ${sectionTitle}
Region: ${region}
Description: ${description}

Requirements: ${template.requirements}
Typical Content: ${template.typical_content}
Guidance: ${template.guidance}

Create a comprehensive, professional document section that:
1. Follows ICH M4 guidelines exactly
2. Uses appropriate regulatory language and terminology
3. Includes proper section numbering and headers
4. Provides substantive content appropriate for ${region} regulatory submission
5. Incorporates best practices from the CTD field manual
6. Ensures compliance with current regulatory expectations

The content should be ready for inclusion in an actual regulatory submission. Use formal, precise language appropriate for regulatory review. Include relevant subsections, tables, and formatting as appropriate for this section type.

Generate the complete section content:`;

    const response = await openai.chat.completions.create({
      model: 'gpt-4o', // the newest OpenAI model is "gpt-4o" which was released May 13, 2024. do not change this unless explicitly requested by the user
      messages: [
        {
          role: 'system',
          content:
            'You are an expert regulatory affairs professional and medical writer specializing in CTD/eCTD document preparation. Generate authentic, submission-ready regulatory content following ICH guidelines.',
        },
        {
          role: 'user',
          content: prompt,
        },
      ],
      max_tokens: 4000,
      temperature: 0.3, // Lower temperature for more consistent, professional regulatory writing
    });

    return {
      content: response.choices[0].message.content,
      metadata: {
        sectionCode,
        sectionTitle,
        region,
        generated: new Date().toISOString(),
        template: template,
        wordCount: response.choices[0].message.content.split(' ').length,
      },
    };
  } catch (error) {
    console.error('Error generating CTD section content:', error);
    throw error;
  }
}

// API endpoint for CTD section generation
router.post('/generate-section', async (req, res) => {
  try {
    const { sectionCode, sectionTitle, description, region = 'US' } = req.body;

    if (!sectionCode || !sectionTitle) {
      return res.status(400).json({
        error: 'Missing required fields: sectionCode and sectionTitle are required',
      });
    }

    console.log(`Generating CTD section ${sectionCode}: ${sectionTitle} for region ${region}`);

    const result = await generateCtdSectionContent(sectionCode, sectionTitle, description, region);

    res.json({
      success: true,
      ...result,
    });
  } catch (error) {
    console.error('CTD section generation error:', error);

    if (error.message.includes('OpenAI API key')) {
      return res.status(401).json({
        error: 'OpenAI API key not configured',
        message: 'Please provide your OpenAI API key to enable CTD section generation.',
      });
    }

    res.status(500).json({
      error: 'Failed to generate CTD section',
      message: error.message,
    });
  }
});

// Get available CTD sections and their templates
router.get('/sections', (req, res) => {
  const sections = Object.entries(CTD_SECTION_TEMPLATES).map(([code, template]) => ({
    code,
    ...template,
  }));

  res.json({
    success: true,
    sections,
  });
});

