// Load pyramid templates
async function loadPyramidTemplates() {
  try {
    const templatePath = path.join(__dirname, '../../templates/ectd/fda_pyramid_templates.xml');
    const xmlData = await fs.readFile(templatePath, 'utf8');
    const parser = new xml2js.Parser();
    const result = await parser.parseStringPromise(xmlData);
    return result;
  } catch (error) {
    console.error('Error loading pyramid templates:', error);
    throw error;
  }
}

// Get all pyramid templates
router.get('/pyramid-templates', async (req, res) => {
  try {
    const templates = await loadPyramidTemplates();
    const pyramidTemplates = templates['ectd-pyramid-templates']['pyramid-template'];

    const templateList = pyramidTemplates.map(template => ({
      id: template.$.id,
      type: template.$.type,
      title: template.title[0],
      description: template.description[0]
    }));

    res.json({
      success: true,
      templates: templateList
    });
  } catch (error) {
    res.status(500).json({
      success: false,
      error: 'Failed to load pyramid templates'
    });
  }
});

// Get specific pyramid template by type
router.get('/pyramid-templates/:type', async (req, res) => {
  try {
    const { type } = req.params;
    const templates = await loadPyramidTemplates();
    const pyramidTemplates = templates['ectd-pyramid-templates']['pyramid-template'];

    const template = pyramidTemplates.find(t => t.$.type.toLowerCase() === type.toLowerCase());

    if (!template) {
      return res.status(404).json({
        success: false,
        error: `Template type '${type}' not found`
      });
    }

    // Process template structure for frontend
    const processedTemplate = {
      id: template.$.id,
      type: template.$.type,
      title: template.title[0],
      description: template.description[0],
      modules: []
    };

    // Process modules
    Object.keys(template).forEach(key => {
      if (key.startsWith('module-')) {
        const moduleNum = key.split('-')[1];
        const moduleData = template[key][0];

        const module = {
          number: moduleNum,
          title: moduleData.$.title,
          sections: []
        };

        // Process sections
        Object.keys(moduleData).forEach(sectionKey => {
          if (sectionKey.startsWith('section')) {
            const sectionData = moduleData[sectionKey];
            if (Array.isArray(sectionData)) {
              sectionData.forEach(section => {
                module.sections.push(processSection(section));
              });
            } else {
              module.sections.push(processSection(sectionData));
            }
          }
        });

        processedTemplate.modules.push(module);
      }
    });

    res.json({
      success: true,
      template: processedTemplate
    });
  } catch (error) {
    res.status(500).json({
      success: false,
      error: 'Failed to load template'
    });
  }
});

// Process section data
function processSection(section) {
  const processed = {
    id: section.$.id,
    title: section.$.title,
    required: section.$.required === 'true',
    guidance: section.guidance ? section.guidance[0] : '',
    contentType: section['content-type'] ? section['content-type'][0] : '',
    estimatedPages: section['estimated-pages'] ? section['estimated-pages'][0] : '',
    wordCount: section['word-count'] ? section['word-count'][0] : '',
    autoGenerated: section['auto-generated'] === 'true',
    subsections: []
  };

  // Process content requirements
  if (section['content-requirements']) {
    processed.contentRequirements = [];
    const items = section['content-requirements'][0].item;
    if (items) {
      processed.contentRequirements = Array.isArray(items) ? items : [items];
    }
  }

  // Process subsections recursively
  if (section.subsection) {
    const subsections = Array.isArray(section.subsection) ? section.subsection : [section.subsection];
    processed.subsections = subsections.map(sub => processSection(sub));
  }

  return processed;
}

