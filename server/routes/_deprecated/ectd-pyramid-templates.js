function parseECTDTemplates(xmlData) {
  const parser = new xml2js.Parser();
  return new Promise((resolve, reject) => {
    parser.parseString(xmlData, (err, result) => {
      if (err) {
        reject(err);
        return;
      }

      const templates = result['ectd-pyramid-templates']['pyramid-template'].map(template => ({
        id: template.$.id,
        name: template.title[0],
        description: template.description[0],
        module: template.module ? template.module[0] : null,
        type: template.$.type
      }));
      resolve(templates);
    });
  });
}

