// Generate checklist from template
function generateChecklist(template) {
  const checklist = {
    templateType: template.$.type,
    title: template.title[0],
    items: []
  };

  // Process modules to create checklist items
  Object.keys(template).forEach(key => {
    if (key.startsWith('module-')) {
      const moduleNum = key.split('-')[1];
      const moduleData = template[key][0];

      const moduleItem = {
        id: `module-${moduleNum}`,
        type: 'module',
        title: `Module ${moduleNum}: ${moduleData.$.title}`,
        required: true,
        completed: false,
        children: []
      };

      // Process sections
      Object.keys(moduleData).forEach(sectionKey => {
        if (sectionKey.startsWith('section')) {
          const sectionData = moduleData[sectionKey];
          const sections = Array.isArray(sectionData) ? sectionData : [sectionData];

          sections.forEach(section => {
            const sectionItem = createChecklistItem(section, moduleNum);
            moduleItem.children.push(sectionItem);
          });
        }
      });

      checklist.items.push(moduleItem);
    }
  });

  return checklist;
}

// Create checklist item from section
function createChecklistItem(section, moduleNum) {
  const item = {
    id: section.$.id,
    type: 'section',
    title: section.$.title,
    required: section.$.required === 'true',
    completed: false,
    guidance: section.guidance ? section.guidance[0] : '',
    children: []
  };

  // Add content requirements as sub-items
  if (section['content-requirements']) {
    const items = section['content-requirements'][0].item;
    if (items) {
      const requirements = Array.isArray(items) ? items : [items];
      requirements.forEach((req, index) => {
        item.children.push({
          id: `${section.$.id}-req-${index}`,
          type: 'requirement',
          title: req,
          required: true,
          completed: false
        });
      });
    }
  }

  // Process subsections
  if (section.subsection) {
    const subsections = Array.isArray(section.subsection) ? section.subsection : [section.subsection];
    subsections.forEach(sub => {
      const subItem = createChecklistItem(sub, moduleNum);
      item.children.push(subItem);
    });
  }

  return item;
}

// Validate document against pyramid template
router.post('/pyramid-templates/:type/validate', async (req, res) => {
  try {
    const { type } = req.params;
    const { document, content } = req.body;

    const templates = await loadPyramidTemplates();
    const pyramidTemplates = templates['ectd-pyramid-templates']['pyramid-template'];

    const template = pyramidTemplates.find(t => t.$.type.toLowerCase() === type.toLowerCase());

    if (!template) {
      return res.status(404).json({
        success: false,
        error: `Template type '${type}' not found`
      });
    }

    const validationResult = validateAgainstTemplate(document, content, template);

    res.json({
      success: true,
      validation: validationResult
    });
  } catch (error) {
    res.status(500).json({
      success: false,
      error: 'Validation failed'
    });
  }
});

// Validate document against template
function validateAgainstTemplate(document, content, template) {
  const validation = {
    isValid: true,
    score: 0,
    totalChecks: 0,
    issues: [],
    completeness: {}
  };

  // Basic content validation
  if (content) {
    validation.totalChecks++;
    if (content.length > 100) {
      validation.score++;
    } else {
      validation.issues.push({
        type: 'content_length',
        severity: 'warning',
        message: 'Document content appears to be too short'
      });
    }
  }

  // Template-specific validation based on type
  const templateType = template.$.type.toLowerCase();

  if (templateType === 'ind') {
    validateINDSpecific(content, validation);
  } else if (templateType === 'nda') {
    validateNDASpecific(content, validation);
  } else if (templateType === 'bla') {
    validateBLASpecific(content, validation);
  } else if (templateType === '510k') {
    validate510KSpecific(content, validation);
  }

  // Calculate final score
  validation.completenessPercentage = validation.totalChecks > 0 ? 
    Math.round((validation.score / validation.totalChecks) * 100) : 0;

  validation.isValid = validation.completenessPercentage >= 70;

  return validation;
}

// IND-specific validation
function validateINDSpecific(content, validation) {
  const requiredElements = [
    'investigational new drug',
    'clinical investigation',
    'safety',
    'pharmacology',
    'toxicology'
  ];

  requiredElements.forEach(element => {
    validation.totalChecks++;
    if (content && content.toLowerCase().includes(element)) {
      validation.score++;
    } else {
      validation.issues.push({
        type: 'missing_element',
        severity: 'critical',
        message: `Missing required element: ${element}`
      });
    }
  });
}

