router.post('/citations/resolve', citationsResolveHandler);
router.get('/audit', auditHandler);
router.get('/evidence', listEvidenceHandler);
router.get('/evidence/inbox', listEvidenceInboxHandler);
router.get('/evidence/:id/download', evidenceDownloadHandler);
