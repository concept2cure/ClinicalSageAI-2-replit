import { Router } from 'express';
import multer from 'multer';
import generateCER2V from './generate.post';
import intelligenceHandler from './intelligence.post';
import exportHandler from './export.post';
import manifestHandler from './manifest.post';
import workbenchHandler from './workbench.get';
import classifyEvidenceHandler from './evidence-classify.post';
import linkClaimHandler from './link-claim.post';
import linkStandardHandler from './link-standard.post';
import linkOutcomeHandler from './link-outcome.post';
import readinessHandler from './readiness.get';
import preflightHandler from './preflight.post';
import verifyHandler from './verify.post';
import createClaimHandler from './claims.post';
