router.patch('/evidence/:id', updateEvidenceHandler);
router.patch('/evidence/bulk', bulkEvidenceHandler);
router.post('/evidence/dedupe', dedupeEvidenceHandler);
router.post('/evidence/classify', classifyEvidenceHandler);
router.post('/claims/:id/link', linkClaimHandler);
router.post('/standards/:id/link', linkStandardHandler);
router.post('/outcomes/:id/link', linkOutcomeHandler);

