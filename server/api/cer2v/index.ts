const router = Router();
const upload = multer({ storage: multer.memoryStorage() });

router.post('/generate', generateCER2V);
router.post('/intelligence', intelligenceHandler);
router.post('/export', exportHandler);
router.post('/manifest', manifestHandler);
router.get('/workbench', workbenchHandler);
router.get('/readiness', readinessHandler);
router.post('/preflight', preflightHandler);
router.post('/verify', verifyHandler);
router.post('/claims', createClaimHandler);
router.patch('/claims/:id', updateClaimHandler);
router.post('/standards', createStandardHandler);
