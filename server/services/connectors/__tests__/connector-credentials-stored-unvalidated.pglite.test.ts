/**
 * Storing a connector credential does not record it as validated.
 *
 * What the code used to do: storeCredentials wrote `is_valid = true,
 * last_validated_at = NOW()` on insert and on replace, with no validation call —
 * a credential nobody had tried was recorded as validated just now, and
 * describe_capabilities / the connector catalog built on that. A replaced
 * secret inherited a fresh "validated" stamp too.
 *
 * Now a stored credential is unvalidated (`is_valid` NULL — the column is
 * nullable — and `last_validated_at` NULL), and it is still the credential a
 * search tries: only one marked invalid is withheld.
 *
 * Real DDL on PGlite, generated by drizzle-kit from the Drizzle model in
 * shared/schema.ts (no migration creates the table; drizzle push does). The
 * registry, the Google Drive connector and the encryption are real; outbound
 * HTTP is stubbed.
 */
import { createRequire } from 'node:module';
import { generateKeyPairSync } from 'node:crypto';
import { PGlite } from '@electric-sql/pglite';
import { afterAll, afterEach, beforeAll, beforeEach, describe, expect, it, vi } from 'vitest';
import { connectorCredentials } from '../../../../shared/schema';

const holder = vi.hoisted(() => ({ pg: null as unknown as import('@electric-sql/pglite').PGlite }));
const pool = vi.hoisted(() => ({
  query: (text: string, params?: unknown[]) => holder.pg.query(text, params as unknown[]),
}));
vi.mock('../../../db.js', () => ({ pool, getPool: () => pool }));
vi.mock('../../../db', () => ({ pool, getPool: () => pool }));

import { getConnectorCatalog, searchConnectors, storeCredentials } from '../connector-registry.js';

const ORG = 1;
const row = async () =>
  (
    await holder.pg.query<{ is_valid: boolean | null; last_validated_at: Date | null }>(
      `SELECT is_valid, last_validated_at FROM connector_credentials WHERE organization_id = $1 AND connector_id = 'google_drive'`,
      [ORG],
    )
  ).rows[0];
const privateKey = () =>
  generateKeyPairSync('rsa', { modulusLength: 2048 }).privateKey.export({ type: 'pkcs8', format: 'pem' }).toString();
const connectDrive = () => storeCredentials(ORG, 'google_drive', { clientId: 'svc@acme.iam', clientSecret: privateKey() });

const realFetch = globalThis.fetch;
const driveSearches: string[] = [];
const json = (body: unknown) =>
  new Response(JSON.stringify(body), { status: 200, headers: { 'content-type': 'application/json' } });

beforeAll(async () => {
  holder.pg = new PGlite();
  await holder.pg.exec(`CREATE TABLE organizations (id SERIAL PRIMARY KEY, name TEXT); INSERT INTO organizations (id, name) VALUES (${ORG}, 'acme');`);
  // drizzle-kit's ESM entry has an unsupported bundled require; use its CJS entry.
  const kit = createRequire(import.meta.url)('drizzle-kit/api') as typeof import('drizzle-kit/api');
  for (const statement of await kit.generateMigration(kit.generateDrizzleJson({}), kit.generateDrizzleJson({ connectorCredentials }))) {
    await holder.pg.exec(statement);
  }
}, 60_000);
afterAll(async () => {
  await holder.pg?.close();
});

beforeEach(async () => {
  await holder.pg.exec('DELETE FROM connector_credentials');
  driveSearches.length = 0;
  globalThis.fetch = vi.fn(async (input: string | URL | Request) => {
    const url = String(input);
    if (url === 'https://oauth2.googleapis.com/token') return json({ access_token: 'drive-token', expires_in: 3600 });
    driveSearches.push(url);
    return json({ files: [] });
  }) as typeof fetch;
});
afterEach(() => {
  globalThis.fetch = realFetch;
});

describe('connector credentials: stored is not validated', () => {
  it('a stored credential is recorded unvalidated', async () => {
    await connectDrive();
    const r = await row();
    expect(r.is_valid, 'a credential nobody tried was recorded valid').toBeNull();
    expect(r.last_validated_at, 'a validation that never ran was dated').toBeNull();
  });

  it("replacing a credential clears the earlier credential's validation", async () => {
    await connectDrive();
    await holder.pg.exec(`UPDATE connector_credentials SET is_valid = true, last_validated_at = '2026-01-01'`);
    await connectDrive();
    const r = await row();
    expect(r.is_valid, 'the replaced secret inherited a validated flag').toBeNull();
    expect(r.last_validated_at).toBeNull();
  });

  it('an unvalidated credential is still the one a search tries', async () => {
    await connectDrive();
    const [res] = await searchConnectors(ORG, ['google_drive'], { keywords: ['protocol'] });
    expect(res.error, 'a stored, unvalidated credential was treated as not configured').toBeUndefined();
    expect(driveSearches.length).toBeGreaterThan(0);
    const drive = (await getConnectorCatalog(ORG)).find(c => c.id === 'google_drive');
    expect(drive?.configured).toBe(true);
  });

  it('a credential marked invalid is withheld from a search', async () => {
    await connectDrive();
    await holder.pg.exec(`UPDATE connector_credentials SET is_valid = false`);
    const [res] = await searchConnectors(ORG, ['google_drive'], { keywords: ['protocol'] });
    expect(res.error).toBeDefined();
    expect(driveSearches).toEqual([]);
  });
});
