import crypto from 'node:crypto';
import { getPool } from '../../db';
import { enforceAuthorLineage } from '../clinical-regulatory-evidence/lineage-gate';
import { resolveSignerIdentity } from '../part11/resolve-signer-identity';
import { resolveSignerOrgRole } from '../part11/resolve-signer-role';

/**
 * Where the content came from. Names the version's origin, the provenance
 * description and the default backend service — each of which used to say
 * "compute job" whatever the caller was.
 */
export type WritebackSource = 'compute' | 'proposal_accept' | 'export';

interface WritebackInput {
  organizationId: number;
  projectId: number;
  /** The person who acted. Their name and organization role are read from the membership record. */
  userId: number;
  title: string;
  content: string;
  ctdSection?: string;
  /** The compute job, for a compute writeback; no other source has one. */
  sourceJobId?: string;
  surfaceKey: string;
  sourceType: WritebackSource;
  metadata?: Record<string, unknown>;
  sourceDescription?: string;
  /** The route the act came through. Required: the default named a route that does not exist. */
  backendRoute: string;
  backendService?: string;
  /** The request's address, when the caller has the request. Never invented. */
  ipAddress?: string | null;
  auditAction?: string;
  auditMetadata?: Record<string, unknown>;
}

/* REMOVED 2026-10-15 — attribution this writer made up. Every governed artifact
   it created (a compute result, an accepted conversation proposal, a governed
   export: the device technical file among them) was recorded with
     - ip_address '127.0.0.1' on the provenance event and the GxP audit row —
       the server's loopback, not where the act came from;
     - user_role 'system' on the audit row, for a person's act;
     - actor_name 'Artifact Compute Plane' / 'Export Governance Plane' and a
       user_name slug of it beside the real user id;
     - "Initial artifact generated by compute job <id>" as the version's
       description, and a finalize route that does not exist as its backend
       route, whatever the caller.
   The person's name and role now come from the membership record in the same
   transaction (resolveSignerIdentity / resolveSignerOrgRole — a user who is
   not a member of the organization cannot create its governed record), the
   address is the request's or says it was not captured, and the origin is the
   caller's. */
const ORIGIN: Record<WritebackSource, { service: string; version: (i: WritebackInput) => string; description: (i: WritebackInput) => string }> = {
  compute: {
    service: 'artifact-compute',
    version: (i) => `Initial version from compute job ${i.sourceJobId}`,
    description: (i) => `Compute surface ${i.surfaceKey}`,
  },
  proposal_accept: {
    service: 'conversation-os',
    version: () => 'Initial version from an accepted conversation proposal',
    description: () => 'Accepted conversation proposal',
  },
  export: {
    service: 'export-governance',
    version: (i) => `Initial version recorded for a governed ${i.surfaceKey} export`,
    description: (i) => `Governed ${i.surfaceKey} export`,
  },
};

/** The audit row's ip_address is NOT NULL; an address nobody captured says so. */
const IP_NOT_CAPTURED = 'ip-not-captured';

export async function registerArtifactWithGovernance(input: WritebackInput): Promise<{
  artifactId: string;
  version: number;
  artifactTitle: string;
  artifactStatus: string;
  placementState: 'placed' | 'unplaced';
  provenanceEventId: string;
  auditId: string;
}> {
  const pool = getPool();
  const client = await pool.connect();
  const now = new Date();
  const externalArtifactId = `artifact_${Date.now()}_${crypto.randomBytes(4).toString('hex')}`;
  const contentHash = crypto.createHash('sha256').update(input.content).digest('hex');
  const sourceType = input.sourceType;
  const origin = ORIGIN[sourceType];
  if (!origin) throw new Error(`registerArtifactWithGovernance: unknown source ${String(sourceType)}`);
  if (!input.backendRoute?.trim()) throw new Error('registerArtifactWithGovernance: backendRoute is required');
  if (sourceType === 'compute' && !input.sourceJobId) {
    throw new Error('registerArtifactWithGovernance: a compute writeback names its job');
  }

  try {
    await client.query('BEGIN');

    // Who acted, from the membership record, in this transaction. Throws
    // (and the whole writeback rolls back) when the user is not a member.
    const actor = await resolveSignerIdentity(client, input.userId, input.organizationId, 'artifact_writeback');
    const actorRole = await resolveSignerOrgRole(input.userId, input.organizationId, client);

    const artifactInsert = await client.query(
      `INSERT INTO concept2cure_artifacts (
        artifact_id, project_id, organization_id, type, category, title, content,
        content_hash, version, ctd_section, status, created_by_id, metadata, created_at, updated_at
      ) VALUES ($1,$2,$3,'regulatory_document','document',$4,$5,$6,1,$7,'draft',$8,$9,$10,$10)
      RETURNING id, artifact_id, version`,
      [
        externalArtifactId,
        input.projectId,
        input.organizationId,
        input.title,
        input.content,
        contentHash,
        input.ctdSection ?? null,
        input.userId,
        JSON.stringify({
          ...(input.sourceJobId ? { computeJobId: input.sourceJobId } : {}),
          surfaceKey: input.surfaceKey,
          source: sourceType,
          governed: true,
          provenancePresent: true,
          auditPresent: true,
          ...(input.metadata ?? {}),
        }),
        now,
      ]
    );

    const artifactPk = artifactInsert.rows[0].id;

    const versionInsert = await client.query(
      `INSERT INTO concept2cure_artifact_versions (
        artifact_id, organization_id, version, content, content_hash, change_description, created_by_id, created_at, updated_at
      ) VALUES ($1,$2,1,$3,$4,$5,$6,$7,$7)
      RETURNING id`,
      [
        artifactPk,
        input.organizationId,
        input.content,
        contentHash,
        origin.version(input),
        input.userId,
        now,
      ]
    );

    /* Span lineage, in the same transaction as the artifact and its version
       (ledger L177, the pattern of L160's writers). This is the shared writer
       behind compute output, an accepted conversation-OS proposal and a
       generated draft, so a regulatory document created through any of its four
       callers used to arrive with provenance and an audit row but no record of
       where its sentences came from.

       Author, not source: the content reaches this function already composed and
       no retrieved Data Room chunks travel with it, so the honest attribution is
       that the acting user asserted these clauses — inventing a source here
       would be the dishonesty the attribution subsystem exists to prevent. A
       lineage gap rolls the whole writeback back, artifact included. */
    await enforceAuthorLineage(
      client,
      input.organizationId,
      { documentTable: 'concept2cure_artifacts', documentId: String(artifactPk) },
      input.content,
      String(input.userId),
    );

    const provenanceEventId = `prov_${Date.now()}_${crypto.randomBytes(4).toString('hex')}`;
    await client.query(
      // No `updated_at` — the table has no such column (see the note at the
      // matching insert in exportGovernance.ts). Postgres rejects an unknown
      // column at PLAN time, so this failed on every writeback.
      `INSERT INTO concept2cure_provenance_events (
        event_id, artifact_id, artifact_version_id, organization_id, event_type, event_action,
        actor_id, actor_name, actor_email, details, source_description, backend_route, backend_service, ip_address, created_at
      ) VALUES ($1,$2,$3,$4,'generation','artifact_compute_writeback',$5,$6,$7,$8,$9,$10,$11,$12,$13)`,
      [
        provenanceEventId,
        artifactPk,
        versionInsert.rows[0].id,
        input.organizationId,
        input.userId,
        actor.name,
        actor.email,
        JSON.stringify({
          ...(input.sourceJobId ? { computeJobId: input.sourceJobId } : {}),
          generatedAt: now.toISOString(),
          ...(input.metadata ?? {}),
        }),
        input.sourceDescription ?? origin.description(input),
        input.backendRoute,
        input.backendService ?? origin.service,
        input.ipAddress ?? null,
        now,
      ]
    );

    const auditAction = input.auditAction ?? 'CREATE';
    const auditId = `audit_${Date.now()}_${crypto.randomBytes(4).toString('hex')}`;
    await client.query(
      // No created_at/updated_at — see the note at the matching insert in
      // exportGovernance.ts. `timestamp` is this table's only time column.
      `INSERT INTO regulatory_audit_logs (
        audit_id, organization_id, entity_type, entity_id, action, action_category,
        previous_value, new_value, user_id, user_name, user_role, ip_address,
        is_gxp_relevant, timestamp, metadata
      ) VALUES ($1,$2,'artifact',$3,$4,'data-change',NULL,$5,$6,$7,$8,$9,TRUE,$10,$11)`,
      [
        auditId,
        input.organizationId,
        externalArtifactId,
        auditAction,
        JSON.stringify({ title: input.title, ...(input.sourceJobId ? { sourceJobId: input.sourceJobId } : {}) }),
        input.userId,
        actor.name,
        actorRole,
        input.ipAddress ?? IP_NOT_CAPTURED,
        now,
        JSON.stringify({
          source: input.surfaceKey,
          surfaceKey: input.surfaceKey,
          ...(input.auditMetadata ?? {}),
        }),
      ]
    );

    await client.query('COMMIT');

    return {
      artifactId: artifactInsert.rows[0].artifact_id,
      version: artifactInsert.rows[0].version,
      artifactTitle: input.title,
      artifactStatus: 'draft',
      placementState: input.ctdSection ? 'placed' : 'unplaced',
      provenanceEventId,
      auditId,
    };
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}
