#!/usr/bin/env node
/**
 * Self-test for scripts/ci/check-route-ownership-matrix.mjs
 * (ci:route-ownership-matrix and ci:route-ownership-matrix:check).
 *
 * The gate keeps docs/reports/route-ownership-matrix-latest.md — the committed
 * review artifact that tells a reviewer who owns each mounted /api prefix and
 * which route-mount warnings sit on it — in step with
 * docs/reports/route-mount-audit-latest.json. CI regenerates that JSON
 * (ci:audit-route-mounts:no-regression) immediately before running the --check,
 * so --check compares the COMMITTED matrix against the matrix the CURRENT
 * mounts produce. On the current tree it passes, so its failure branch never
 * fires in normal use, and a guard whose failure branch has never been seen
 * has not been tested (CLAUDE.md, working agreement).
 *
 * The defect it exists for is review evidence that no longer describes the
 * code: a new warning on an owned prefix (or a prefix that changed hands) that
 * never reaches the artifact the "Review Gate" checkbox is ticked against, and
 * the converse, a matrix hand-edited to read `none` where the audit says
 * otherwise. Its second history is in its own header comment: an earlier shape
 * of the matrix carried per-run metadata (generatedAt, mount/warning counts),
 * which drift on every audit run and "would make this gate fail forever in CI".
 * The near-miss cases below pin that the gate does NOT fail on that drift, nor
 * on the same facts arriving in a different order.
 *
 * Each case builds a throwaway docs/reports/ pair in its own temp directory and
 * runs the gate as a subprocess with that directory as its cwd. The gate
 * resolves both paths against cwd, so the command CI runs is the command under
 * test; no copy of the gate is patched. The expected matrix is written out
 * literally here, not generated by the gate, so a generator that drops a column
 * cannot agree with itself and pass.
 *
 * Every stale case then runs the remedy the gate prints (the write mode) and
 * asserts the regenerated matrix carries the row that changed and that --check
 * passes after it — the gate's stale message does not name the row, so this is
 * where the selftest locates the site.
 *
 * SELFTEST_GATE_PATH points the cases at a different copy of the gate, so a
 * mutant can be shown to fail them.
 *
 * Not asserted, because the gate does not implement it (observed, not pinned):
 *   - The stale message does not say which row differs.
 *   - A warning on a path with no ownership row never reaches the matrix, so a
 *     new one does not make it stale. On the current tree 5 of the 8 audit
 *     warnings are on such paths (/api/cmc/module3-os, /api/ectd,
 *     /api/submissions, /api/v1, /api/mdx).
 *   - issues.errors are not represented in the matrix at all.
 *
 * Usage: node scripts/ci/check-route-ownership-matrix.selftest.mjs   (exit 0 = every case held)
 */

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const TAG = '[ci:route-ownership-matrix:selftest]';
const GATE = process.env.SELFTEST_GATE_PATH
  ? path.resolve(process.cwd(), process.env.SELFTEST_GATE_PATH)
  : path.join(path.dirname(fileURLToPath(import.meta.url)), 'check-route-ownership-matrix.mjs');

if (!fs.existsSync(GATE)) {
  console.error(`${TAG} gate not found: ${GATE}`);
  process.exit(1);
}

const AUDIT_REL = 'docs/reports/route-mount-audit-latest.json';
const MATRIX_REL = 'docs/reports/route-ownership-matrix-latest.md';
const STALE = 'Route ownership matrix is stale. Regenerate with npm run ci:route-ownership-matrix';

// ── Fixture ─────────────────────────────────────────────────────────────────
// The audit JSON in the shape scripts/ci/audit-route-mounts.mjs writes it, cut
// down from the real one: five owned prefixes in owners-file order (not sorted),
// multi-use-prefix warnings on two of them and on one unowned path.

const BASE_AUDIT = {
  target:
    'server/index.ts,server/bootstrap/register-*.ts,server/startup/routes.ts,server/startup/inline-endpoints.ts,server/startup/middleware.ts',
  generatedAt: '2026-09-11T21:14:32.289Z',
  mounts: 329,
  errors: 0,
  warnings: 3,
  issues: {
    errors: [],
    warnings: [
      { type: 'multi-use-prefix', path: '/api/ai', key: null },
      { type: 'multi-use-prefix', path: '/api/cmc', key: null },
      { type: 'multi-use-prefix', path: '/api/v1', key: null },
    ],
  },
  ownership: [
    { prefix: '/api', owner: 'Platform API Gateway', contact: 'server/index.ts' },
    { prefix: '/api/auth', owner: 'Identity Access', contact: 'server/routes/auth.ts' },
    { prefix: '/api/documents', owner: 'Authoring Governance', contact: 'server/routes/documents-unified.ts' },
    { prefix: '/api/ai', owner: 'AI Platform', contact: 'server/services/ai-gateway/' },
    { prefix: '/api/cmc', owner: 'CMC Platform', contact: 'server/routes/cmc*.ts' },
  ],
};

const ROW = {
  api: '| `/api` | Platform API Gateway | `server/index.ts` | none |',
  ai: '| `/api/ai` | AI Platform | `server/services/ai-gateway/` | multi-use-prefix |',
  auth: '| `/api/auth` | Identity Access | `server/routes/auth.ts` | none |',
  cmc: '| `/api/cmc` | CMC Platform | `server/routes/cmc*.ts` | multi-use-prefix |',
  documents: '| `/api/documents` | Authoring Governance | `server/routes/documents-unified.ts` | none |',
};

/** The committed artifact, exactly as a correct regeneration writes it. */
const MATRIX = [
  '# Route Ownership Matrix (Required Review Artifact)',
  '',
  '- Source: `docs/reports/route-mount-audit-latest.json`',
  '',
  '## Prefix Ownership',
  '',
  '| Prefix | Owner | Contact | Warning types |',
  '|---|---|---|---|',
  ROW.api,
  ROW.ai,
  ROW.auth,
  ROW.cmc,
  ROW.documents,
  '',
  '## Review Gate',
  '',
  '- [ ] Reviewer confirmed any non-`none` warning types are accepted or remediated.',
  '',
].join('\n');

const audit = (mutate) => {
  const a = structuredClone(BASE_AUDIT);
  mutate?.(a);
  return a;
};
const owner = (a, prefix) => a.ownership.find((o) => o.prefix === prefix);

// ── Cases ───────────────────────────────────────────────────────────────────
// audit / matrix: content to write, or null to leave the file absent.
// regenerate: after the failing --check, run the write mode the gate names and
//   require these rows in what it writes (and not the stale ones), then
//   require --check to pass.

const cases = [
  // ── GREEN ──
  {
    name: 'GREEN — the committed matrix matches the audit',
    audit: audit(),
    matrix: MATRIX,
    expect: 0,
    mustSay: ['Route ownership matrix check passed'],
  },
  {
    name: 'GREEN (near miss) — the audit was re-run: new generatedAt, mount and warning counts, same ownership',
    // The gate header's own history: per-run metadata drifts on every CI run.
    audit: audit((a) => {
      a.generatedAt = '2026-10-01T08:00:00.000Z';
      a.mounts = 341;
      a.warnings = 4;
      a.errors = 0;
      a.issues.warnings.push({ type: 'multi-use-prefix', path: '/api/ai', key: null });
    }),
    matrix: MATRIX,
    expect: 0,
    mustSay: ['Route ownership matrix check passed'],
  },
  {
    name: 'GREEN (near miss) — same owners and warnings, in a different order',
    audit: audit((a) => {
      a.ownership.reverse();
      a.issues.warnings.reverse();
    }),
    matrix: MATRIX,
    expect: 0,
    mustSay: ['Route ownership matrix check passed'],
  },
  {
    name: 'GREEN — with no matrix committed, the write mode produces exactly the reviewed artifact',
    audit: audit(),
    matrix: null,
    args: [],
    expect: 0,
    mustSay: [`Route ownership matrix written: ${MATRIX_REL}`],
    writtenEquals: MATRIX,
  },

  // ── RED: a warning the reviewer never sees ──
  {
    name: 'RED — a new warning on an owned prefix, matrix not regenerated',
    audit: audit((a) => a.issues.warnings.push({ type: 'shadow-risk', path: '/api/auth', key: null })),
    matrix: MATRIX,
    expect: 1,
    mustSay: [STALE],
    regenerate: {
      has: ['| `/api/auth` | Identity Access | `server/routes/auth.ts` | shadow-risk |'],
      hasNot: [ROW.auth],
    },
  },
  {
    name: 'RED — a second warning type on an already-warned prefix (not just none → some)',
    audit: audit((a) => a.issues.warnings.push({ type: 'shadow-risk', path: '/api/ai', key: null })),
    matrix: MATRIX,
    expect: 1,
    mustSay: [STALE],
    regenerate: {
      has: ['| `/api/ai` | AI Platform | `server/services/ai-gateway/` | multi-use-prefix, shadow-risk |'],
      hasNot: [ROW.ai],
    },
  },
  {
    name: 'RED — the matrix was hand-edited to read `none` where the audit has a warning',
    audit: audit(),
    matrix: MATRIX.replace(ROW.ai, ROW.ai.replace('multi-use-prefix', 'none')),
    expect: 1,
    mustSay: [STALE],
    regenerate: { has: [ROW.ai] },
  },
  {
    name: 'RED — a warning was remediated but the matrix still reports it',
    audit: audit((a) => {
      a.issues.warnings = a.issues.warnings.filter((w) => w.path !== '/api/cmc');
    }),
    matrix: MATRIX,
    expect: 1,
    mustSay: [STALE],
    regenerate: {
      has: ['| `/api/cmc` | CMC Platform | `server/routes/cmc*.ts` | none |'],
      hasNot: [ROW.cmc],
    },
  },

  // ── RED: ownership that changed under the artifact ──
  {
    name: 'RED — a prefix changed owner, matrix not regenerated',
    audit: audit((a) => {
      owner(a, '/api/documents').owner = 'Vault Records';
    }),
    matrix: MATRIX,
    expect: 1,
    mustSay: [STALE],
    regenerate: {
      has: ['| `/api/documents` | Vault Records | `server/routes/documents-unified.ts` | none |'],
      hasNot: [ROW.documents],
    },
  },
  {
    name: 'RED — a prefix changed contact file, matrix not regenerated',
    audit: audit((a) => {
      owner(a, '/api/auth').contact = 'server/routes/auth-sso.ts';
    }),
    matrix: MATRIX,
    expect: 1,
    mustSay: [STALE],
    regenerate: {
      has: ['| `/api/auth` | Identity Access | `server/routes/auth-sso.ts` | none |'],
      hasNot: [ROW.auth],
    },
  },
  {
    name: 'RED — a newly owned prefix (with its own warning) is absent from the matrix',
    audit: audit((a) => {
      a.ownership.push({ prefix: '/api/vault', owner: 'Vault Records', contact: 'server/routes/vault.ts' });
      a.issues.warnings.push({ type: 'multi-use-prefix', path: '/api/vault', key: null });
    }),
    matrix: MATRIX,
    expect: 1,
    mustSay: [STALE],
    regenerate: { has: ['| `/api/vault` | Vault Records | `server/routes/vault.ts` | multi-use-prefix |'] },
  },
  {
    name: 'RED — a prefix left the owners file but the matrix still lists it',
    audit: audit((a) => {
      a.ownership = a.ownership.filter((o) => o.prefix !== '/api/cmc');
    }),
    matrix: MATRIX,
    expect: 1,
    mustSay: [STALE],
    regenerate: { has: [ROW.ai, ROW.documents], hasNot: ['`/api/cmc`'] },
  },

  // ── RED: missing inputs fail closed ──
  {
    name: 'RED — the review artifact is not committed at all',
    audit: audit(),
    matrix: null,
    expect: 1,
    mustSay: ['Required review artifact missing', MATRIX_REL],
  },
  {
    name: 'RED — the audit JSON is missing (an error, not an empty matrix)',
    audit: null,
    matrix: MATRIX,
    expect: 1,
    mustSay: ['Route mount audit file missing', AUDIT_REL],
  },
];

// ── Runner ──────────────────────────────────────────────────────────────────

const tmpRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'route-ownership-matrix-'));

function runGate(cwd, args) {
  const r = spawnSync(process.execPath, [GATE, ...args], { cwd, encoding: 'utf8' });
  return { code: r.status ?? 1, out: `${r.stdout ?? ''}${r.stderr ?? ''}` };
}

function setUp(c, i) {
  const dir = path.join(tmpRoot, `case-${i}`);
  fs.mkdirSync(path.join(dir, 'docs', 'reports'), { recursive: true });
  if (c.audit) fs.writeFileSync(path.join(dir, AUDIT_REL), `${JSON.stringify(c.audit, null, 2)}\n`);
  if (c.matrix !== null) fs.writeFileSync(path.join(dir, MATRIX_REL), c.matrix);
  return dir;
}

let failed = 0;
try {
  cases.forEach((c, i) => {
    const dir = setUp(c, i);
    const problems = [];
    const transcript = [];

    const { code, out } = runGate(dir, c.args ?? ['--check']);
    transcript.push(out);
    if (code !== c.expect) problems.push(`expected exit ${c.expect}, got ${code}`);
    for (const s of c.mustSay ?? []) {
      if (!out.includes(s)) problems.push(`output did not say ${JSON.stringify(s)}`);
    }

    if (c.writtenEquals !== undefined) {
      const p = path.join(dir, MATRIX_REL);
      const written = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
      if (written !== c.writtenEquals) problems.push('written matrix differs from the reviewed artifact');
    }

    if (c.regenerate) {
      const regen = runGate(dir, []);
      transcript.push(regen.out);
      if (regen.code !== 0) problems.push(`regeneration exited ${regen.code}`);
      const p = path.join(dir, MATRIX_REL);
      const written = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : '';
      const lines = new Set(written.split('\n'));
      for (const row of c.regenerate.has ?? []) {
        if (!lines.has(row)) problems.push(`regenerated matrix lacks row ${JSON.stringify(row)}`);
      }
      for (const s of c.regenerate.hasNot ?? []) {
        const present = s.startsWith('|') ? lines.has(s) : written.includes(s);
        if (present) problems.push(`regenerated matrix still has ${JSON.stringify(s)}`);
      }
      const recheck = runGate(dir, ['--check']);
      transcript.push(recheck.out);
      if (recheck.code !== 0) problems.push(`--check after regeneration exited ${recheck.code}`);
    }

    const ok = problems.length === 0;
    if (!ok) failed += 1;
    console.log(`  ${ok ? '✓' : '✗'} ${c.name}  (exit ${code}, expected ${c.expect})`);
    if (!ok) {
      for (const p of problems) console.log(`      ${p}`);
      console.log(
        transcript
          .join('')
          .split('\n')
          .map((l) => `      | ${l}`)
          .join('\n'),
      );
    }
  });
} finally {
  fs.rmSync(tmpRoot, { recursive: true, force: true });
}

if (failed) {
  console.error(`\n${TAG} FAIL — ${failed}/${cases.length} cases did not hold (gate: ${GATE})`);
  process.exit(1);
}
console.log(`\n${TAG} ${cases.length} passed — the gate fails on what it exists to catch.`);
