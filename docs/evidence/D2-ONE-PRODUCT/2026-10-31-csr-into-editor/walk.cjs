const { chromium } = require('playwright');
const fs = require('fs'); const path = require('path');
const BASE = 'http://localhost:5000'; const OUT = path.join(__dirname, 'csr-freeze'); fs.mkdirSync(OUT, { recursive: true });
const P = '547ccb6c-b31d-4d8a-83d7-0d9594943265', DOC = '08c06993-152b-4f5a-8606-82cba40db7b3';
(async () => {
  const dl = await (await fetch(`${BASE}/api/auth/dev-login`, { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: BASE }, body: JSON.stringify({ email: 'jm.smith@concept2cure.pro' }) })).json();
  const sess = await (await fetch(`${BASE}/api/v1/auth/session`, { headers: { Authorization: `Bearer ${dl.accessToken}`, Origin: BASE } })).json();
  const browser = await chromium.launch();
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
  const expiry = new Date(Date.now() + 23 * 3600 * 1000).toISOString();
  await context.addInitScript(([t, r, e, u]) => { for (const s of [localStorage, sessionStorage]) { s.setItem('trialsage_access_token', t); s.setItem('trialsage_refresh_token', r); s.setItem('trialsage_token_expiry', e); s.setItem('trialsage_user', u); } }, [dl.accessToken, dl.refreshToken, expiry, JSON.stringify(sess.user)]);
  const page = await context.newPage();
  const log = []; page.on('pageerror', e => log.push('PAGEERROR ' + String(e.message).slice(0, 200)));
  page.on('console', m => { if (m.type() === 'error') log.push('CONSOLE ' + m.text().slice(0, 200)); });
  page.on('response', r => { if (r.status() >= 400) log.push(`${r.status()} ${r.request().method()} ${r.url().replace(BASE, '')}`); });
  const step = (s) => console.info(`\n--- ${s}`);
  await page.goto(`${BASE}/concept2cure/document-authoring?program=${P}&documentId=${DOC}`, { waitUntil: 'domcontentloaded' });
  for (let i = 0; i < 240 && await page.getByText(/Loading surface/).count(); i++) await page.waitForTimeout(1000);
  await page.waitForTimeout(5000);
  const panel = page.locator('details[aria-label="Build from the study’s data"]');
  step('panel present: ' + await panel.count());
  await panel.locator('summary').click(); await page.waitForTimeout(3000);
  console.info((await panel.innerText()).slice(0, 900));
  await panel.screenshot({ path: path.join(OUT, '01-panel-no-study-data.png') });
  step('choose source and preview');
  await panel.getByLabel('Clinical source', { exact: true }).selectOption({ label: 'BX-512-201 study data (synthetic) · v1.0 · approved' });
  await panel.getByRole('button', { name: 'Preview clinical tables' }).click();
  await panel.getByLabel('Clinical table preview').waitFor({ timeout: 30000 });
  console.info((await panel.getByLabel('Clinical table preview').innerText()).slice(0, 500));
  await panel.screenshot({ path: path.join(OUT, '02-preview.png') });
  step('freeze');
  await panel.getByRole('button', { name: 'Freeze as this document’s study data' }).click();
  await panel.getByRole('button', { name: /Build CSR draft/ }).first().waitFor({ timeout: 30000 }).catch(e => log.push('no build button: ' + e.message.slice(0, 120)));
  console.info((await panel.innerText()).slice(0, 1400));
  await panel.screenshot({ path: path.join(OUT, '03-frozen-and-build.png') });
  const sel = await panel.getByLabel(/Study data/).evaluate(el => ({ value: el.value, text: el.options[el.selectedIndex]?.text })).catch(() => null);
  console.info('STUDY DATA SELECTED:', JSON.stringify(sel));
  step('queue a build');
  const build = panel.getByRole('button', { name: /Build CSR draft/ }).first();
  if (await build.count()) { await build.click(); await page.waitForTimeout(8000); console.info((await panel.innerText()).slice(0, 1600)); await panel.screenshot({ path: path.join(OUT, '04-build-queued.png') }); }
  console.info('\nLOG', JSON.stringify(log, null, 1));
  await browser.close();
})().catch(e => { console.error('FAILED', e); process.exit(1); });
